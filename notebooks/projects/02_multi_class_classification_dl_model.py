# 2. build out model
from torch import nn

class MulyiClassClassificationModel(nn.Module):
  def __init__ (self, in_features, out_features, hidden_unites=10):
    super().__init__()

    self.three_layers = nn.Sequential(
        nn.Linear(in_features=in_features, out_features=hidden_unites),
        nn.ReLU(),
        nn.Linear(in_features=hidden_unites, out_features=hidden_unites),
        nn.ReLU(),
        nn.Linear(in_features=hidden_unites, out_features=out_features),
    )

  def forward(self, x):
    return self.three_layers(x)

model_1 = MulyiClassClassificationModel(in_features=2, out_features=4)
model_1.state_dict()

# Create loss fun and opt
import torch.optim as optim


