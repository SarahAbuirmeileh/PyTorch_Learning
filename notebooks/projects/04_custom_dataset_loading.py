## 0. Import pytorch and set up device-ognostic code

import torch
device = "cuda" if torch.cuda.is_available()  else "cpu"
device

# 1. download the dataset from github

import requests
import zipfile
from pathlib import Path


data_path = Path("data/")
image_path = data_path / "pizza _steak_sushi"

if image_path.is_dir():
  print(f"{image_path} already exists, skipping downloading ....")
else:
  print(f"{image_path} doesn't exist, creating one ....")
  image_path.mkdir(parents=True, exist_ok=True)


# Downloading our data
with open(data_path / "pizza_steak_sushi.zip", "wb") as f: # wb: write binary

  request = requests.get("https://github.com/mrdbourke/pytorch-deep-learning/raw/refs/heads/main/data/pizza_steak_sushi.zip")
  print("Downloading pizza, steak, suhsi data...")
  f.write(request.content)

# Unzip pizza, steak, sushi data
with zipfile.ZipFile(data_path / "pizza_steak_sushi.zip", "r") as zip_ref:
  print("Unzipping pizza, steak and sushi data...")
  zip_ref.extractall(image_path)

train_dir = image_path / "train"
test_dir = image_path / "test"

# now we have all images downloaded
# 2. now convert them into tensors


# Get the path for all iamges
image_path_list = list(image_path.glob("*/*/*.jpg"))
image_path_list

len(image_path_list)

from PIL import Image

first_image_path = image_path_list[0]
image_class = first_image_path.parent.stem

Image.open(first_image_path)

# know the shape of the images

import numpy as np

for path in image_path_list:
  img = Image.open(path)
  img_array = np.asarray(img)
  print(img_array.shape)

from typing_extensions import dataclass_transform
# The data is [h, w, c]

# Transforme them into a into sth can fit pytorch


from torchvision import transforms

data_transform = transforms.Compose([
    transforms.Resize(size=(64, 64)),
    transforms.ToTensor()
])

data_transform(img=img)

# 3.convert the tensors into dataset

from torchvision import datasets

train_dataset = datasets.ImageFolder(root=train_dir,
                                  transform=data_transform, target_transform=None)
test_dataset = datasets.ImageFolder(root=test_dir,
                                 transform=data_transform,
                                 target_transform=None)

# 4. convert dataset -> dataloader

from torch.utils.data import DataLoader

train_dataloader = DataLoader(dataset=train_dataset,
                              batch_size=32,
                              shuffle=True)
test_dataloader = DataLoader(dataset=test_dataset,
                              batch_size=32,
                              shuffle=False)

