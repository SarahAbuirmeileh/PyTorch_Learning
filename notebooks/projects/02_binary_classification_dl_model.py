# 1. Make our classification data

import sklearn # for ML, like PyTorch for DL

from sklearn.datasets import make_circles

RANDOM_STATE = 42

n_samples = 1000
x, y = make_circles(n_samples=n_samples,
                 noise = 0.03,
                 random_state=RANDOM_STATE)

x[:10], y[:10]

import matplotlib.pyplot as plt

plt.scatter(x=x[:, 0],
            y=x[:, 1],
            c=y,#color it with labels
            cmap=plt.cm.RdYlBu)

x.shape, y.shape

# 1.2 Split our data

from sklearn.model_selection import train_test_split

X_train, X_test, y_train, y_test = train_test_split(x, y, test_size=0.2)

from numpy import dtype
# 1.3 Turn data into tensors
import torch

X_train, X_test = torch.from_numpy(X_train).type(torch.float), torch.from_numpy(X_test).type(torch.float)
y_train, y_test = torch.from_numpy(y_train).type(torch.float), torch.from_numpy(y_test).type(torch.float)

# 2. Build the model

# 2.1 Create device ognistic gode

device = "cuda" if torch.cuda.is_available() else "cpu"

# Send the data  into the correct device
X_train, X_test = X_train.to(device), X_test.to(device)
y_train, y_test = y_train.to(device), y_test.to(device)

# 2.2 Build the model
from torch import nn

class LinearClassification(nn.Module):
  def __init__(self, in_featurs, out_features, hidden_units=8):
    super().__init__()

    self.three_linear_layers = nn.Sequential(
        nn.Linear(in_features=in_featurs, out_features=hidden_units ),
        nn.ReLU(),
        nn.Linear(in_features=hidden_units, out_features=hidden_units ),
        nn.ReLU(),
        nn.Linear(in_features=hidden_units, out_features=out_features)
    )

  def forward(self, x):
    return self.three_linear_layers(x)

# y_train.float(), y_test,float()
X_train.dtype, X_test.dtype

# 2.3 Make a prediction

torch.manual_seed(42)
torch.cuda.manual_seed(42)

model_0 = LinearClassification(in_featurs=2, out_features=1, hidden_units=10).to(device)

model_0.eval()
with torch.inference_mode():
  y_logits = model_0(X_test.float())

y_preds = torch.round(torch.sigmoid(y_logits)).squeeze()
y_preds[:10]

y_preds.shape, y_test.shape

torch.eq(y_preds, y_test)

# Build loss and optmizer
import torch.optim

loss_fn = nn.BCEWithLogitsLoss()

optimizer = torch.optim.SGD(params=model_0.parameters(),
                            lr=0.1)

# ! pip install torchmetrics

from torchmetrics import Accuracy

# 3. Build train and test loop

epochs = 2000

for epoch in range(epochs):
  model_0.train()

  y_logits = model_0(X_train).squeeze() # Squeezed to match 1D y_train shape
  y_preds = torch.round(torch.sigmoid(y_logits))

  loss = loss_fn(y_logits, y_train)

  optimizer.zero_grad()

  loss.backward()

  optimizer.step()

  # Testing loop
  model_0.eval()
  with torch.inference_mode():
    y_test_logits = model_0(X_test).squeeze() # Squeezed to match 1D y_test shape
    y_test_preds = torch.round(torch.sigmoid(y_test_logits))

    test_loss = loss_fn(y_test_logits, y_test)
    acc = Accuracy(task="binary", num_classes=2)(y_test_preds, y_test)

    if epoch % 100 == 0:
      print(f"Epoch: {epoch} | test Loss: {test_loss} | acc: {acc}")

