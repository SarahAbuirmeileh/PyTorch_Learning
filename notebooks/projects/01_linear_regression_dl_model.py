import torch

# Steps:
# 1. Create our data
# 2. Build nn model
# 3. Train the model (loss fun + Optimizer)

# 1. Create our data
# equation y = a + b*x

# Create device agnostic code
device = "cuda" if torch.cuda.is_available() else "cpu"

start = 0
end = 1
step = 0.02

bias = 0.3
weight = 0.7

# input
X = torch.arange(start, end, step)

# output
y = bias + weight * x

# 1.2 Split our data
train_split = int(0.8 * len(x))

# x_train = x[:train_split]
# y_train = y[:train_split]
# x_test = x[train_split:]
# y_test = y[train_split:]

X_train, y_train = X[:train_split], y[:train_split]
X_test, y_test = X[train_split:], y[train_split:]

import matplotlib.pyplot as plt

def plot_predictions(train_data=X_train,
                     train_labels=y_train,
                     test_data=X_test,
                     test_labels=y_test,
                     predictions=None):

  plt.figure(figsize=(10, 7))

  # Plot training data in blue
  plt.scatter(train_data, train_labels, c="b", s=4, label="Training data")

  # Plot test data in green
  plt.scatter(test_data, test_labels, c="g", s=4, label="Testing data")

  if predictions is not None:
    # Plot the predictions in red (predictions were made on the test data)
    plt.scatter(test_data, predictions, c="r", s=4, label="Predictions")

  # Show the legend
  plt.legend(prop={"size": 14});

# 2. Build the model

import torch.nn as nn

class LinearRegressionModel(nn.Module):
  def __init__(self):
    super().__init__()

    # Define the paramters with random value
    # self.weight = nn.Parameter(torch.rand(1,
    #                                       requires_grad=True,
    #                                       dtype=torch.float))
    # self.bias = nn.Parameter(torch.rand(1,
    #                                     requires_grad=True,
    #                                     dtype=torch.float))
    
    # Or create a linear layer (this will do the same as the above)
    # and it will be responsible for creating the parameters
    
    self.linear_layer = nn.Linear(in_features=1,
                                  out_features=1)

  def forward(self, x: torch.tensor)->torch.tensor:
    # return self.weight * x + self.bias
    return self.linear_layer(x)

# 2.2 see out model

RANDOM_SEED = 42
torch.manual_seed(RANDOM_SEED)

model = LinearRegressionModel()
model.to(device)

print(model.parameters())
print(model.state_dict())

# make a prediction

with torch.inference_mode():
  y_preds = model(X_test)
print(f"first prediction (befor optmization): \n{y_preds} \n Ground Truth: \n {y_test}")

# plot the predictions
plot_predictions(predictions=y_preds)

# 3. Train the model

import torch.optim as optim


# loss fun
loss_fn = torch.nn.L1Loss()

# optimizer
optimizer = optim.SGD(params=model.parameters(), lr=0.01)

# Training Loop

epochs = 100

# Track different values
epoch_count = []
loss_values = []
test_loss_values = []


for epoch in range(epochs):
  # put the model in the tranign mood

  # Why we did it in each loop? why not just once outside the loop
  model.train()

  # make predictions
  y_preds = model(X_train)

  # Calculate the loss
  loss = loss_fn(y_preds, y_train)

  # delete the gradients from previous iteration -> it get accumelated by defult in pyTorch
  optimizer.zero_grad()

  # Calculate the gradients (see how chaning the paramters will change the loss)
  loss.backward()

  # Edit the parameters
  optimizer.step()


  # Testing
  # test our model while traning (we might compare the reuslts of this traning with other, and to see how good out model is becoming)

  model.eval()
  with torch.inference_mode():
    test_preds = model(X_test)
    test_loss = loss_fn(test_preds, y_test)

    if epoch % 10 == 0:
      epoch_count.append(epoch)
      loss_values.append(loss)
      test_loss_values.append(test_loss)
      print(f"Epoch: {epoch} | Loss: {loss} | Test Loss: {test_loss}")

with torch.inference_mode():
  y_pred = model(X_test)

plot_predictions(predictions=y_pred)

# Save our model
from pathlib import Path

MODEL_PATH = Path("models")
MODEL_PATH.mkdir(parents=True, exist_ok=True)

MODEL_NAME = "01_pytorch_linear_regression_model.pth"
MODEL_SAVE_PATH = MODEL_PATH / MODEL_NAME

torch.save(obj=model.state_dict(),
           f=MODEL_SAVE_PATH)

# Load our model

loaded_dict_state = torch.load(f=MODEL_SAVE_PATH)

# Create instance form our model class
loaded_model = LinearRegressionModel()

# Load the state dict
loaded_model.load_state_dict(loaded_dict_state)

# Test the predictions from the original and loaded model

model.eval()
with torch.inference_mode():
  y_preds = model(X_test)

loaded_model.eval()
with torch.inference_mode():
  loaded_y_preds = loaded_model(X_test)

